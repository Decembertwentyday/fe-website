/**
 * ============================================================
 * 文件说明：MUI（Material-UI）全局主题配置文件
 *
 * 什么是主题（Theme）？
 * 主题就像整个网站的"设计规范说明书"：
 *   - 颜色：主色调是什么？背景是什么颜色？
 *   - 字体：用什么字体？
 *   - 断点：屏幕多宽算"手机"？多宽算"PC"？
 *   - 组件默认行为：按钮默认有没有点击水波纹？
 *
 * 在 providers.tsx 里通过 <ThemeProvider theme={customTheme}> 注入全局，
 * 之后所有 MUI 组件都自动应用这个主题，不用每个组件单独设置颜色。
 * ============================================================
 */

import { createTheme } from '@mui/material';
// ↑ createTheme：MUI 提供的函数，用来创建自定义主题对象

const customTheme = createTheme({
  // ─────────────────────────────────────────────────────────────
  // 响应式断点配置（Breakpoints）
  // 决定了 xs/sm/md/lg/xl 对应多少像素宽
  // 在组件里可以这样用：sx={{ display: { xs: 'none', md: 'flex' } }}
  // 意思：手机上不显示，中等屏幕及以上显示 flex
  // ─────────────────────────────────────────────────────────────
  breakpoints: {
    values: {
      xs: 0, // 0px ~ 599px → 超小屏（手机）
      sm: 600, // 600px ~ 899px → 小屏（平板竖屏）
      md: 900, // 900px ~ 1199px → 中等屏（平板横屏）
      lg: 1200, // 1200px ~ 1535px → 大屏（普通电脑）
      xl: 1536, // 1536px+ → 超大屏（大显示器）
    },
  },

  // ─────────────────────────────────────────────────────────────
  // 调色板配置（Palette）
  // ─────────────────────────────────────────────────────────────
  palette: {
    mode: 'dark', // ← 深色模式（整体暗色背景），MUI 会自动调整文字颜色为亮色
    background: {
      default: '#171A1F;', // ← 页面背景色：深灰近黑（注意：末尾有个多余的分号，不影响运行）
    },
    primary: { main: '#E5FF65' },
    // ↑ 主色调：黄绿色（#E5FF65）
    // 这个颜色会用于：按钮、高亮文字、选中状态等
    // 你会看到整个网站的品牌色就是这个荧光黄绿
  },

  // ─────────────────────────────────────────────────────────────
  // 排版配置（Typography）
  // ─────────────────────────────────────────────────────────────
  typography: {
    fontFamily: 'Poppins',
    // ↑ 全站字体：Poppins（Google Fonts 上的英文字体，现代感强）
    // 注意：中文字符不在 Poppins 字体覆盖范围，会自动 fallback 到系统默认字体
    // Poppins 在 global.css 里通过 @import 引入
  },

  // ─────────────────────────────────────────────────────────────
  // 组件默认属性覆盖（Components Override）
  // ─────────────────────────────────────────────────────────────
  components: {
    MuiButtonBase: {
      // ↑ MuiButtonBase 是所有 MUI 按钮/图标按钮的基础组件
      defaultProps: {
        disableRipple: true, // ← 禁用点击水波纹效果（Ripple）
        disableTouchRipple: true, // ← 禁用触摸水波纹效果
        // 为什么禁用水波纹？
        // 这是一个设计选择：EtchMarket 追求简洁扁平的 Web3 风格，
        // 水波纹动效会显得"太 Material"，与整体设计语言不符
      },
    },
  },
});

export default customTheme;
// ↑ 导出主题对象，在 providers.tsx 里被 <ThemeProvider> 使用
